def qa(s, heading, items, size=20, gap=0.3):
    """確認問題・解答の枚。●見出しは本文の枚の結論の一文と同じ大きさ・色（28pt の主色の太字）で、1問ずつ横いっぱいの薄い灰の箱に。
    items = [(番号, 本文)]。番号は「1-1」の形（原稿HTMLの「1-1 に答える」ボタンになる。箱の文字が「1-1　問題文」で始まる）。
    以前は文字だけを左の上から置き、見出しが細い灰色で、上と右が大きく空いて間延びしていた（外から見た採点の指摘）"""
    s.heading("{ab:" + heading + "}", size=28)
    x0, x1 = deck.wide
    y = deck.area["top"]
    for k, txt in items:
        h = max(1.0, (txt.count("\n") + 1) * line_height_in(size) + 0.5)
        s.rect(x0, y, x1 - x0, h, fill=C.LIGHT, text="{ab:" + k + "}　" + txt, size=size, align="l", name="確認問題の箱")
        y += h + gap


