def qa(s, items, size=22, gap=0.45):
    """確認問題・解答の本文。items = [(番号, 本文)]。番号は「1-1」の形（原稿HTMLの「1-1 に答える」ボタンになる）"""
    s.at(1.0, 2.0)
    for j, (k, txt) in enumerate(items):
        s.p("{b:" + k + "}　" + txt, size=size, gap=gap if j < len(items) - 1 else 0.2)

